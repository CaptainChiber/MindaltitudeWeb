function detectPreferredLanguage() {
  const saved = localStorage.getItem("mindaltitude-lang");
  if (saved === "fr" || saved === "en") return saved;

  const languages = navigator.languages && navigator.languages.length
    ? navigator.languages
    : [navigator.language || "en"];

  const prefersFrench = languages.some(language =>
    String(language).toLowerCase().startsWith("fr")
  );

  return prefersFrench ? "fr" : "en";
}

function setLanguage(language, persist = true) {
  document.documentElement.lang = language;

  document.querySelectorAll("[data-i18n]").forEach(element => {
    const key = element.getAttribute("data-i18n");
    const value = translations[language][key];
    if (value) element.innerHTML = value;
  });

  const enButton = document.getElementById("lang-en");
  const frButton = document.getElementById("lang-fr");

  if (enButton) enButton.classList.toggle("active", language === "en");
  if (frButton) frButton.classList.toggle("active", language === "fr");

  if (persist) localStorage.setItem("mindaltitude-lang", language);
}

document.addEventListener("DOMContentLoaded", () => {
  const enButton = document.getElementById("lang-en");
  const frButton = document.getElementById("lang-fr");

  if (enButton) enButton.addEventListener("click", () => setLanguage("en"));
  if (frButton) frButton.addEventListener("click", () => setLanguage("fr"));

  setLanguage(detectPreferredLanguage(), false);
});
